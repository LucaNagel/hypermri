"""Notebook views of spectrum phase evolution using shared signal calculations."""

import ipywidgets as widgets
import matplotlib.cm as cm
import matplotlib.pyplot as plt
import numpy as np
from IPython.display import display
from mpl_toolkits.axes_grid1 import make_axes_locatable

from hypermri.analysis.spectroscopy.processing import norm
from hypermri.analysis.spectroscopy.signals import (
    combine_isochromats,
    propagate_isochromats,
)


class SpeckSimulator:
    """Explore the phase evolution of explicitly supplied spectra.

    Parameters
    ----------
    specs : list of numpy.ndarray
        One or more one-dimensional component-weight spectra in arbitrary signal
        units. Singleton axes are squeezed; each spectrum must match xaxis_hz.
    xaxis_hz : numpy.ndarray
        Shared frequency bins in Hz, in the same order as each spectrum.
    labels : list of str, optional
        One display label per spectrum. Missing labels are generated by index.

    Raises
    ------
    AssertionError
        If specs is not a list or label and spectrum counts differ.

    Notes
    -----
    Construction retains array references without simulating or constructing widgets.
    Plot methods initialize notebook controls. The numerical propagation owner is
    analysis.spectroscopy.signals; no relaxation or noise model is added here.

    Examples
    --------
    >>> simulator = SpeckSimulator([np.array([1., 2.])], np.array([0., 250.]))
    >>> simulator.simulate([0., .001])
    """

    def __init__(self, specs, xaxis_hz, labels=None):
        """Retain spectra, frequency bins and optional display labels.

        Parameters
        ----------
        specs : list of numpy.ndarray
            Component weights in signal units, one one-dimensional spectrum per entry.
        xaxis_hz : numpy.ndarray
            Matching shared frequency bins in Hz.
        labels : list of str, optional
            One label per spectrum, or generated index labels.

        Returns
        -------
        None
            Retains input references without constructing a plot or simulating.

        Raises
        ------
        AssertionError
            If spectrum input is not a list or label counts disagree.
        """
        assert isinstance(specs, list), "Provide a list of one or multiple spectra."
        self.spectra = [np.squeeze(s) for s in specs]

        self.fbins = xaxis_hz

        if labels is None:
            self.labels = [f"Nr. {i + 1}" for i in range(len(self.spectra))]
        else:
            assert len(labels) == len(self.spectra)
            self.labels = labels

        # this is a relict from the CSImulator
        self.voxel_selection = {l: i for i, l in enumerate(self.labels)}

        self.magnitudes = None
        self.phases = None
        self.timepoints = None

    def propagate(self, A_spec, t, offset=0):
        """Evolve spectral weights using the shared isochromat calculation.

        Parameters
        ----------
        A_spec : array_like
            Component weights matching ``self.fbins`` in arbitrary signal units.
        t : float
            Evolution time in seconds.
        offset : float, optional
            Initial phase offset in radians.

        Returns
        -------
        vectors, phases_rad : numpy.ndarray
            Complex component signals and unwrapped phases in radians, with the
            broadcast input shape. Inputs are not mutated; evaluation is eager.

        Raises
        ------
        ValueError
            If weights and frequency shapes cannot broadcast.
        """
        return propagate_isochromats(A_spec, self.fbins, t, offset)

    def spectrum2phase(self, A_spec, t, offset=0, return_all=False):
        """Return effective magnitude and principal phase after evolution.

        Parameters
        ----------
        A_spec : array_like
            Component weights matching ``self.fbins`` in arbitrary signal units.
        t : float
            Evolution time in seconds.
        offset : float, optional
            Initial phase offset in radians.
        return_all : bool, optional
            Also return the complex component sum when True.

        Returns
        -------
        tuple
            Magnitude in signal units and phase in radians in ``[-pi, pi]``;
            optionally the complex sum. Deterministic, eager, without mutation.

        Raises
        ------
        ValueError
            If weights and frequency shapes cannot broadcast.
        """
        vectors, _ = self.propagate(A_spec, t, offset)
        result = combine_isochromats(vectors)
        return result if return_all else result[:2]

    def simulate(self, timepoints, offsets=False):
        """Simulate integrated spectra at explicit evolution times.

        Parameters
        ----------
        timepoints : sequence of float
            Evolution times in seconds, in the desired frame order.
        offsets : bool or sequence of float, optional
            False or None uses zero phase. True draws offsets uniformly from [0, pi)
            using NumPy's global random state. Explicit offsets are radians per spectrum.

        Returns
        -------
        None
            Stores complex_data, magnitudes and phases (radians), initially ordered
            (time, spectrum) with singleton axes squeezed, plus timepoints and offsets.
            Input spectra are not modified; explicit offsets make evaluation deterministic.

        Raises
        ------
        ValueError, IndexError
            If timepoints, component weights or offset counts are inconsistent.
        """
        if offsets is True:
            self.offsets = np.random.uniform(0, np.pi, len(self.spectra))
        elif offsets is None or offsets is False:
            self.offsets = np.zeros(len(self.spectra))
        else:
            self.offsets = offsets

        N_specs = len(self.spectra)
        phases = np.zeros((len(timepoints), N_specs))
        magnitudes = np.zeros((len(timepoints), N_specs))
        complex_data = np.zeros((len(timepoints), N_specs), dtype="complex")
        for i, spec in enumerate(self.spectra):
            for j, t in enumerate(timepoints):
                (
                    magnitudes[j, i],
                    phases[j, i],
                    complex_data[j, i],
                ) = self.spectrum2phase(
                    spec, t, offset=self.offsets[i], return_all=True
                )

        self.complex_data = np.squeeze(complex_data)
        self.phases = np.squeeze(phases)
        self.magnitudes = np.squeeze(magnitudes)
        self.timepoints = np.array(timepoints)

    def add_offset(self, offsets=None):
        """Apply the retained sign-dependent offset correction in place.

        Parameters
        ----------
        offsets : object, optional
            Retained unused legacy argument; stored self.offsets are used.

        Returns
        -------
        None
            Mutates stored phases by the stored offset according to the first phase's
            sign. Requires nonsqueezed time-by-spectrum phase arrays from simulation.

        Raises
        ------
        IndexError, TypeError, AttributeError
            If stored simulation phases or offsets are unavailable or incompatible.
        """
        for i, _ in enumerate(self.spectra):
            if self.phases[0, i] > 0:
                self.phases[..., i] -= self.offsets[i]
            else:
                self.phases[..., i] += self.offsets[i]

    def umpire(self):
        """Reject unavailable UMPIRE phase unwrapping.

        Returns
        -------
        None
            No result is produced.

        Raises
        ------
        NotImplementedError
            Always; UMPIRE is not included in this package build.
        """
        raise NotImplementedError(
            "UMPIRE-based phase unwrapping is not included in this package build."
        )

    def phase2frequency(self):
        """Fit stored unwrapped phases linearly against time.

        Returns
        -------
        None
            Stores freq and freq_err in Hz and yoffset_fit and yoffset_fit_err in
            radians, one value per spectrum. Samples are preserved; fit arrays change.

        Raises
        ------
        AttributeError
            If caller-provided unwrapped_phases or simulation timepoints are unavailable.
        ValueError, RuntimeError
            If SciPy rejects inconsistent data or cannot fit the line.

        Notes
        -----
        UMPIRE is unavailable in this build; callers must supply unwrapped_phases
        explicitly in (time, spectrum) order. SciPy determines fit precision.
        """
        from scipy.optimize import curve_fit

        self.freq = np.zeros(len(self.spectra))
        self.freq_err = np.zeros(len(self.spectra))
        self.yoffset_fit = np.zeros(len(self.spectra))
        self.yoffset_fit_err = np.zeros(len(self.spectra))

        def lin_reg(x, m, t):
            return x * m + t

        for i, _ in enumerate(self.spectra):
            popt, pcov = curve_fit(
                lin_reg, self.timepoints, self.unwrapped_phases[..., i]
            )
            self.freq[i] = popt[0] / (2 * np.pi)  # rad -> Hz
            self.freq_err[i] = np.sqrt(np.diag(pcov))[0] / (2 * np.pi)  # std error
            self.yoffset_fit[i] = popt[1]
            self.yoffset_fit_err[i] = np.sqrt(np.diag(pcov))[1]

    def clocks(self, t_min=0, t_max=3e-3, t_step=0.5e-6):
        """Show interactive polar vectors for the selected spectra.

        Parameters
        ----------
        t_min, t_max : float, optional
            Beginning and exclusive end of the evolution interval in seconds.
        t_step : float, optional
            Positive time increment in seconds.

        Returns
        -------
        None
            Displays a Matplotlib figure and notebook time controls. Signal evolution
            uses the shared deterministic isochromat helper; measured data are preserved.

        Raises
        ------
        AssertionError
            If no spectra are selected.
        ValueError, IndexError
            If the time interval is empty or spectra and frequency bins are inconsistent.
        """
        N = len(self.voxel_selection)

        assert N != 0, "No voxel selection provided!"

        fig, axes = plt.subplots(
            ncols=N, figsize=(9.5, 5.5), subplot_kw={"projection": "polar"}
        )

        if N == 1:
            axes = [axes]

        r_total_t0 = [self.spectrum2phase(spec, t=0)[0] for spec in self.spectra]

        t_range = np.arange(t_min, t_max, t_step)

        self.__layout_adjusted = False  # ugly patch to fix fig.layout + widgets combo

        def plot_func(time_idx, show_total_vec):
            time = t_range[time_idx]
            for i in range(N):
                ax = axes[i]
                spec = self.spectra[i]
                label = self.labels[i]

                zs, true_phases = self.propagate(spec, time)

                rs = norm(np.abs(zs))
                phases = np.angle(zs)

                r_total = np.abs(np.sum(zs)) / r_total_t0[i] * 1.1
                phase_total = np.angle(np.sum(zs))

                ax.clear()
                ax.plot(phases, rs, color="blue")

                if show_total_vec:
                    ax.plot(
                        [r_total, phase_total],
                        [0, r_total],
                        linewidth=2.5,
                        color="orange",
                    )

                # some style improvements
                ax.set_rmax(1.5)
                ax.set_rticks([0.5, 1])  # Less radial ticks
                ax.set
                # Move radial labels away from plotted line
                ax.set_rlabel_position(90)
                ax.grid(True)

                title = r"$\bf{" + str(label) + "}$"
                title += "\n$\\phi_{tot} = $" + f"{phase_total:.3f} rad"
                ax.set_title(title)

            fig.suptitle(f"{time * 1e3:.2f} ms", fontweight=400, fontsize=20, y=0.99)

            if not self.__layout_adjusted:
                fig.tight_layout()
                self.__layout_adjusted = True

        time_slider = widgets.IntSlider(
            value=0,
            min=0,
            max=len(t_range) - 1,
            step=1,
            readout=False,
            layout=widgets.Layout(width="500px"),
        )

        time_play = widgets.Play(
            value=0,
            min=0,
            max=len(t_range) - 1,
            step=1,
            interval=5,
            description="Press play",
            style={"description_width": "initial"},
        )

        play_speed_int = widgets.BoundedIntText(
            value=10,
            min=0,
            max=100,
            step=0.1,
            description="Speed:",
            layout=widgets.Layout(width="140px"),
        )

        widgets.jslink((time_play, "value"), (time_slider, "value"))
        widgets.jslink((time_play, "interval"), (play_speed_int, "value"))

        total_vec_button = widgets.ToggleButton(
            value=True,
            description="Total Vector",
            button_style="",  # 'success', 'info', 'warning', 'danger' or ''
        )
        # put both sliders inside a HBox for nice alignment  etc.
        row1 = widgets.HBox([time_play, time_slider, play_speed_int, total_vec_button])

        ui = widgets.VBox(
            [row1],
            layout=widgets.Layout(display="flex"),
        )

        sliders = widgets.interactive_output(
            plot_func,
            {
                "time_idx": time_slider,
                "show_total_vec": total_vec_button,
            },
        )

        display(ui, sliders)

    def plot(self, mag_cmap="gray", pha_cmap="bwr"):
        """Display stored simulated magnitude and phase frames.

        Parameters
        ----------
        mag_cmap, pha_cmap : str, optional
            Matplotlib colormaps for magnitude (signal units) and phase (radians).

        Returns
        -------
        None
            Displays a figure and notebook frame selector; stored samples are unchanged.

        Raises
        ------
        AssertionError
            If simulate has not been called.
        ValueError, IndexError
            If squeezed simulation arrays cannot be displayed as image frames.
        """
        assert self.timepoints is not None, "You have to call self.simulate() first."

        fig, (ax1, ax2) = plt.subplots(ncols=2, figsize=(9.5, 5))

        # sort out arrangement of colorbar and plot
        divider = make_axes_locatable(ax1)
        cax1 = divider.append_axes("right", size="5%", pad=0.05)
        divider = make_axes_locatable(ax2)
        cax2 = divider.append_axes("right", size="5%", pad=0.05)

        self.__layout_adjusted = False  # ugly patch for fig.tight_layout & widgets

        def plot_func(echo_nr):
            for ax, cax, cmap, data, title, label, ticks in zip(
                [ax1, ax2],
                [cax1, cax2],
                [mag_cmap, pha_cmap],
                [self.magnitudes, self.phases],
                ["magnitude", "phase"],
                ["a.u.", "rad"],
                [[], None],
                strict=False,
            ):
                ax.clear()
                ax.imshow(data[echo_nr], cmap=cmap)
                ax.set_title(title)
                # normalize internal data form 0 to 1
                norm = plt.Normalize(np.nanmin(data), np.nanmax(data))
                # plot the colorbar
                fig.colorbar(
                    cm.ScalarMappable(norm=norm, cmap=cmap),
                    cax=cax,
                    orientation="vertical",
                    label=label,
                    ticks=ticks,
                )

            fig.suptitle(
                f"{self.timepoints[echo_nr] * 1e3:.2f} ms", fontsize=15, fontweight=500
            )

            if not self.__layout_adjusted:
                fig.tight_layout()
                self.__layout_adjusted = True

        echo_slider = widgets.IntSlider(
            value=0,
            min=0,
            max=len(self.timepoints) - 1,
            step=1,
            description="Echo Nr.:",
            style={"description_width": "initial"},
        )

        # put both sliders inside a HBox for nice alignment  etc.
        row1 = widgets.HBox([echo_slider])
        ui = widgets.VBox(
            [row1],
            layout=widgets.Layout(display="flex"),
        )
        sliders = widgets.interactive_output(
            plot_func,
            {
                "echo_nr": echo_slider,
            },
        )
        display(ui, sliders)

    def plot_selection_spectra(self, xmin=-1000, xmax=1000):
        """Plot the selected spectra against their frequency bins.

        Parameters
        ----------
        xmin, xmax : float, optional
            Lower and upper frequency display limits in Hz.

        Returns
        -------
        fig, ax : matplotlib.figure.Figure, matplotlib.axes.Axes
            Displayed figure and axes. Spectra and their arbitrary signal units are
            preserved; no simulation is triggered.

        Raises
        ------
        ValueError
            If spectrum and frequency-axis lengths disagree.
        """
        fig, ax = plt.subplots(figsize=(9, 4))

        N = len(self.voxel_selection)

        for i in range(N):
            ax.plot(self.fbins, self.spectra[i], label=self.labels[i])

        ax.set_xlim(xmin, xmax)
        ax.legend()
        ax.set_xlabel("Frequency [Hz]")
        ax.set_title("Spectra of Voxel Selection")

        fig.tight_layout()
        plt.show()

        return fig, ax

    def plot_selection_phase(self):
        """Plot stored phase evolution for the selected spectra.

        Returns
        -------
        None
            Displays phase in radians against evolution time in milliseconds. Stored
            simulation arrays are not modified.

        Raises
        ------
        AssertionError
            If simulate has not been called.
        ValueError, IndexError
            If stored phase dimensions do not match the selected spectra.
        """
        assert self.timepoints is not None, "You have to call self.simulate() first."

        fig, ax = plt.subplots()

        N = len(self.voxel_selection)
        phase_matrix = np.asarray(self.phases).reshape(
            len(self.timepoints), len(self.spectra)
        )

        for i in range(N):
            spectrum_idx = list(self.voxel_selection.values())[i]
            ax.plot(
                self.timepoints * 1e3,
                phase_matrix[:, spectrum_idx],
                marker="s",
                label=self.labels[i],
            )

        ax.set_xlabel("t [ms]")
        ax.set_ylabel("phase [rad]")
        ax.set_title("Phase Evolution of Voxel Selection")
        ax.legend()
        fig.tight_layout()
